// QA Team A (Tanya) — own back-end instance for TEST-001 / TEST-003. Throwaway harness, not product code.
//
// Database (TEST-001 Q4, PM 2026-11-01, D43; workspace CLAUDE.md rule 4 — no local Postgres): QA's OWN database
// `corner_chat_test_qa_a` on the OWNER'S dev Postgres server, built from the owner's DATABASE_URL in the back repo's .env
// with only the database name swapped. Dropped after every run (`drop`). A local host (127.0.0.1 / localhost) is refused.
// The URL is read in-process and never printed.
// LINE guard (D44 HOLD): LINE_API_BASE is forced to a closed local port and the token to "" in the child's env; process
// env wins over .env (checked 2026-11-01).
//
//   bun backend.ts <back-repo> <secrets.json> up [--gateway http://127.0.0.1:3991] [--paused]   (creates the DB if missing)
//   bun backend.ts <back-repo> <secrets.json> env       print the env (secret values masked)
//   bun backend.ts <back-repo> <secrets.json> reset     drop + recreate QA's own database (only corner_chat_test_qa_a)
//   bun backend.ts <back-repo> <secrets.json> drop      drop QA's own database — run after every test round
//
// Why its own database and port: the 2026-11-01 incident (a second dev server took a row from the shared dev DB,
// DECISIONS "one dev server per DB"). This instance listens on 127.0.0.1:8191. Mail, LINE and FCM point nowhere real.
// secrets.json (outside the repo, generated by QA): { "secretKey", "ownerEmail", "ownerPassword" }.
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { SQL } from "bun";

const [repo, secretsPath, cmd, ...rest] = process.argv.slice(2);
if (!repo || !secretsPath || !cmd) {
  console.error("usage: bun backend.ts <back-repo> <secrets.json> up|env|reset|drop [--gateway URL] [--paused]");
  process.exit(2);
}
const DB_NAME = "corner_chat_test_qa_a";
const PORT = "8191";

function readDotEnv(path: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]!] = m[2]!.replace(/^["']|["']$/g, "");
  }
  return out;
}

const dotenv = readDotEnv(`${repo}/.env`);
const ownerUrl = dotenv.DATABASE_URL; // the owner's URL (host, user, password are his)
if (!ownerUrl) throw new Error("repo .env has no DATABASE_URL — ask the owner through the PM");
const admin = new URL(ownerUrl);
// CREATE / DROP DATABASE go through the server's `postgres` maintenance database, with his credentials, and only for
// DB_NAME (D43 prefix). TEST-001 Q5, PM 2026-11-01, on the owner's words "ให้ไปสร้าง database ใช้ได้" (SYSTEM-FACTS.md).
const maintUrl = new URL(ownerUrl);
maintUrl.pathname = "/postgres";
const adminUrl = maintUrl.toString();
if (!/^corner_chat_test_qa_a$/.test(DB_NAME)) throw new Error("refusing: QA creates/drops only corner_chat_test_qa_a");
if (admin.hostname === "127.0.0.1" || admin.hostname === "localhost" || admin.hostname === "::1") {
  throw new Error("refusing: DATABASE_URL is a local Postgres — rule 4 says the owner's server only (TEST-001 Q4); wait for the owner's URL");
}
const qaUrl = new URL(ownerUrl);
qaUrl.pathname = `/${DB_NAME}`;

if (!existsSync(secretsPath)) {
  const key = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64");
  const pw = Buffer.from(crypto.getRandomValues(new Uint8Array(18))).toString("base64url");
  writeFileSync(secretsPath, JSON.stringify({ secretKey: key, ownerEmail: "owner@qa-a.test", ownerPassword: pw }, null, 2));
}
const secrets = JSON.parse(readFileSync(secretsPath, "utf8"));

const flag = (name: string) => rest.indexOf(name);
const gateway = flag("--gateway") >= 0 ? rest[flag("--gateway") + 1]! : "http://127.0.0.1:3991";
// Mail (TEST-002): default = nowhere (closed port 9, poller off). --imap-port / --smtp-port point at the LOCAL stand-in only.
const opt = (name: string, fallback: string) => (flag(name) >= 0 ? rest[flag(name) + 1]! : fallback);
const imapPort = opt("--imap-port", "9"), smtpPort = opt("--smtp-port", "9"), pollSeconds = opt("--poll", "0");
// --real-mail: the REAL Zimbra host from the repo's .env (owner window only, TEST-002 § Owner window). Never by default.
const realMail = flag("--real-mail") >= 0;
const mailHost = realMail ? (dotenv.ZIMBRA_IMAP_HOST || "mail.entronica.in.th") : "127.0.0.1";
const smtpHost = realMail ? (dotenv.ZIMBRA_SMTP_HOST || "mail.entronica.in.th") : "127.0.0.1";

const env: Record<string, string> = {
  NODE_ENV: "development",
  PORT, HOST: "127.0.0.1",
  DATABASE_URL: qaUrl.toString(),
  DATABASE_URL_TEST: "",
  SECRET_KEY: secrets.secretKey,
  OWNER_EMAIL: secrets.ownerEmail, OWNER_PASSWORD: secrets.ownerPassword, OWNER_NAME: "QA Owner",
  ADMIN_WEB_ORIGIN: "http://localhost:3191",
  ZIMBRA_IMAP_HOST: mailHost, ZIMBRA_IMAP_PORT: realMail ? (dotenv.ZIMBRA_IMAP_PORT || "993") : imapPort,
  ZIMBRA_SMTP_HOST: smtpHost, ZIMBRA_SMTP_PORT: realMail ? (dotenv.ZIMBRA_SMTP_PORT || "465") : smtpPort,
  MAIL_POLL_SECONDS: pollSeconds,
  FILTER_PAUSED: flag("--paused") >= 0 ? "true" : "false",
  LLM_GATEWAY_URL: gateway, LLM_GATEWAY_KEY: "",
  FCM_SERVICE_ACCOUNT_JSON: "",
  LINE_CHANNEL_SECRET: "qa-a-not-a-real-secret", LINE_CHANNEL_ACCESS_TOKEN: "", LINE_API_BASE: "http://127.0.0.1:9",
};

async function adminRun(statement: string) {
  const s = new SQL(adminUrl!);
  try { await s.unsafe(statement); } finally { await s.close(); }
}

if (cmd === "env") {
  for (const [k, v] of Object.entries(env)) {
    const masked = /PASSWORD|SECRET|KEY|DATABASE_URL/.test(k) && v ? "<set>" : v;
    console.log(`${k}=${masked}`);
  }
} else if (cmd === "reset") {
  await adminRun(`DROP DATABASE IF EXISTS "${DB_NAME}" WITH (FORCE)`);
  await adminRun(`CREATE DATABASE "${DB_NAME}"`);
  console.log(`reset ${DB_NAME}`);
} else if (cmd === "drop") {
  await adminRun(`DROP DATABASE IF EXISTS "${DB_NAME}" WITH (FORCE)`);
  console.log(`dropped ${DB_NAME}`);
} else if (cmd === "up") {
  const s = new SQL(adminUrl);
  const [row] = await s`select 1 as ok from pg_database where datname = ${DB_NAME}`;
  await s.close();
  if (!row) { await adminRun(`CREATE DATABASE "${DB_NAME}"`); console.log(`created ${DB_NAME}`); }
  const childEnv = { ...process.env, ...env };
  const mig = Bun.spawnSync(["bun", "scripts/migrate.ts"], { cwd: repo, env: childEnv, stdout: "inherit", stderr: "inherit" });
  if (mig.exitCode !== 0) process.exit(mig.exitCode ?? 1);
  console.log(`starting back end on 127.0.0.1:${PORT}, gateway ${gateway}, db ${DB_NAME}, paused=${env.FILTER_PAUSED}`);
  const child = Bun.spawn(["bun", "src/index.ts"], { cwd: repo, env: childEnv, stdout: "inherit", stderr: "inherit" });
  process.on("SIGINT", () => child.kill());
  process.on("SIGTERM", () => child.kill());
  process.exit(await child.exited);
} else {
  console.error(`unknown command ${cmd}`);
  process.exit(2);
}
