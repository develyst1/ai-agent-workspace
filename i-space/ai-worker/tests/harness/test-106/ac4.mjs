// TEST-106 AC-4: the worker-built Health Board on :3900 — 4 services, then stop QA's own caw-front (pid given) and watch for "ไม่ตอบ" within 13 s with no click; then click "เช็คตอนนี้".
import { createRequire } from 'node:module';
const [front, killPid] = process.argv.slice(2);
const { chromium } = createRequire(front + '/package.json')('@playwright/test');
const note = (c, ok, d) => console.log(`${ok ? 'OK ' : 'BAD'} ${c} — ${d}`);
const b = await chromium.launch({ channel: 'chrome' }); const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
await p.goto('http://127.0.0.1:3900/', { waitUntil: 'networkidle' }); await p.waitForTimeout(4000);
const rows = async () => p.$$eval('tbody tr', (trs) => trs.map((tr) => [...tr.querySelectorAll('td')].map((td) => td.textContent.trim())));
let r = await rows();
note('AC-4 four services, all "ทำงาน", ms and a time, Thai text', r.length === 4 && r.every((x) => x[1] === 'ทำงาน' && /^\d+$/.test(x[2]) && x[3]), JSON.stringify(r));
const color = await p.$eval('tbody tr .up', (e) => getComputedStyle(e).color).catch(() => null);
note('AC-4 "ทำงาน" is green', !!color && /rgb\(\s*\d{1,2},\s*1\d\d|rgb\(\s*\d+,\s*(1[2-9]\d|2\d\d),\s*\d{1,2}\)/.test(color), `color ${color}`);
await p.screenshot({ path: '17-healthboard-all-up.png', fullPage: true });
const t1 = r.map((x) => x[3]).join('|');
await p.waitForTimeout(15000);
const t2 = (await rows()).map((x) => x[3]).join('|');
note('spec 3: re-checks by itself every 10 s', t1 !== t2, `last-check times before ${t1} · after 15 s ${t2}`);
process.kill(Number(killPid)); const tk = Date.now();
await p.waitForTimeout(13000);
r = await rows();
const caw = r.find((x) => x[0].includes('เว็บ CAW'));
note('AC-4 a stopped service turns "ไม่ตอบ" within 13 s, no click', caw?.[1] === 'ไม่ตอบ', `after ${Math.round((Date.now() - tk) / 1000)} s: ${JSON.stringify(caw)}`);
await p.screenshot({ path: '18-healthboard-13s-after-stop.png', fullPage: true });
await p.getByRole('button', { name: 'เช็คตอนนี้' }).click(); await p.waitForTimeout(4500);
r = await rows();
const caw2 = r.find((x) => x[0].includes('เว็บ CAW'));
const red = await p.$eval('tbody tr .down', (e) => getComputedStyle(e).color).catch(() => null);
note('"เช็คตอนนี้" shows it "ไม่ตอบ" (red)', caw2?.[1] === 'ไม่ตอบ', `${JSON.stringify(caw2)} color ${red}`);
await p.screenshot({ path: '19-healthboard-after-checknow.png', fullPage: true });
const body = await p.textContent('body');
note('spec "ไม่ทำ": no login, no alerts, no history', !/login|เข้าสู่ระบบ|แจ้งเตือน|ประวัติ/i.test(body), '');
await b.close();
